def _extract_keywords(question: str) -> str:
    words = [word for word in question.lower().split() if len(word) > 3]
    return ",".join(words)


def _verify_corpus() -> None:
    questions = [question for question, _answer in PAIRS]
    unique_questions = set(questions)
    duplicates = len(questions) - len(unique_questions)

    print(f"[seed_corpus_v2] total pairs: {len(PAIRS)}")
    print(f"[seed_corpus_v2] unique questions: {len(unique_questions)}")
    print(f"[seed_corpus_v2] duplicate questions: {duplicates}")

    over_limit = [
        (question, answer)
        for question, answer in PAIRS
        if len(answer.split()) > 14
    ]
    print(f"[seed_corpus_v2] answers over 14 words: {len(over_limit)}")
    if over_limit:
        for question, answer in over_limit[:10]:
            print(f"  - ({len(answer.split())} words) {question} -> {answer}")

    if duplicates:
        raise ValueError(
            f"PAIRS contains {duplicates} duplicate question(s) — "
            "seed_corpus_v2 requires unique questions before seeding."
        )


def seed(memory_path: str) -> None:
    connection = sqlite3.connect(memory_path)
    inserted = 0
    skipped = 0
    try:
        for question, answer in PAIRS:
            existing = connection.execute(
                "SELECT 1 FROM conversations WHERE question = ? LIMIT 1",
                (question,),
            ).fetchone()
            if existing:
                skipped += 1
                continue

            connection.execute(
                """
                INSERT INTO conversations (question, answer, source, keywords, timestamp)
                VALUES (?, ?, 'human_taught', ?, ?)
                """,
                (question, answer, _extract_keywords(question), time.time()),
            )
            inserted += 1

        connection.commit()
    finally:
        connection.close()

    print(f"Inserted: {inserted}, Skipped: {skipped}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Seed episodic_memory.sqlite3 with the v2 human_taught corpus")
    parser.add_argument("--memory", required=True, help="Path to episodic_memory.sqlite3")
    args = parser.parse_args()

    _verify_corpus()
    seed(args.memory)


if __name__ == "__main__":
    main()

